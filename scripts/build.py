#!/usr/bin/env python3
"""Generate every Gilt app theme from colors.toml and roles.toml.

    python3 scripts/build.py             render templates/ and static/ into the repo
    python3 scripts/build.py --check     fail if any generated file is stale or orphaned
    python3 scripts/build.py --list      print every colour name with its hex
    python3 scripts/build.py --contrast  print the full contrast report

templates/<path> renders to <path>, static/<path> is copied to <path> verbatim.
Placeholders: {{ name }} or {{ name | filter | filter(arg) }}, where name is a
colors.toml key, an [extra] tone, a role, or ansiN. Filters: lower, upper, bare
(no leading #), alpha(0..1) (#RRGGBBAA), mix(other, 0..1) (solid blend toward
another colour). {{ generated }} is the do-not-edit notice.
"""

import argparse
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATES = ROOT / "templates"
STATIC = ROOT / "static"
# Directories whose every file must come from templates/ or static/.
OWNED_DIRS = ["apps"]

GENERATED = "Generated by scripts/build.py from colors.toml and roles.toml, do not edit"
HEX = re.compile(r"^#[0-9A-Fa-f]{6}$")
PLACEHOLDER = re.compile(r"\{\{\s*([A-Za-z_]\w*)\s*((?:\|\s*\w+(?:\([^)]*\))?\s*)*)\}\}")
FILTER = re.compile(r"\|\s*(\w+)(?:\(([^)]*)\))?")


class BuildError(Exception):
    pass


def load_colors():
    """Return {name: hex} for every colour name, plus the parsed roles.toml."""
    colors = tomllib.loads((ROOT / "colors.toml").read_text())
    roles = tomllib.loads((ROOT / "roles.toml").read_text())

    names = {k: v for k, v in colors.items() if isinstance(v, str) and HEX.match(v)}
    for key, value in roles["extra"].items():
        if key in names:
            raise BuildError(f"[extra] {key} already exists in colors.toml")
        if not HEX.match(value):
            raise BuildError(f"[extra] {key} = {value!r} is not #RRGGBB")
        names[key] = value

    palette = dict(names)
    for section, prefix in (("ansi", "ansi"), ("roles", "")):
        for key, ref in roles[section].items():
            name = prefix + key
            if name in names:
                raise BuildError(f"[{section}] {key} collides with an existing colour name")
            if ref not in palette:
                raise BuildError(f"[{section}] {key} = {ref!r} is not in colors.toml or [extra]")
            names[name] = palette[ref]
    return names, roles


def unit(arg, filter_name):
    try:
        a = float(arg)
    except (TypeError, ValueError):
        a = -1
    if not 0 <= a <= 1:
        raise BuildError(f"{filter_name} needs a number between 0 and 1, got {arg!r}")
    return a


def apply_filter(hex_value, name, arg, names):
    if name == "lower":
        return hex_value.lower()
    if name == "upper":
        return hex_value.upper()
    if name == "bare":
        return hex_value.lstrip("#")
    if name == "alpha":
        return f"{hex_value}{round(unit(arg, 'alpha') * 255):02X}"
    if name == "mix":
        # mix(other, t): move t of the way from this colour to other, as a solid colour.
        other, _, t = (arg or "").partition(",")
        other, t = other.strip(), unit(t.strip(), "mix")
        if other not in names:
            raise BuildError(f"mix: unknown colour {other!r}")
        a, b = (bytes.fromhex(h.lstrip("#")[:6]) for h in (hex_value, names[other]))
        return "#" + "".join(f"{round(x + (y - x) * t):02X}" for x, y in zip(a, b))
    raise BuildError(f"unknown filter {name!r}")


def render(text, names, used, source):
    def replace(match):
        name, filters = match.group(1), match.group(2)
        if name == "generated":
            return GENERATED
        if name not in names:
            raise BuildError(f"{source}: unknown colour {name!r}")
        used.add(name)
        value = names[name]
        for f in FILTER.finditer(filters):
            value = apply_filter(value, f.group(1), f.group(2), names)
        return value

    out = PLACEHOLDER.sub(replace, text)
    if "{{" in out:
        line = out[: out.index("{{")].count("\n") + 1
        raise BuildError(f"{source}:{line}: malformed placeholder")
    return out if out.endswith("\n") else out + "\n"


def outputs(names):
    """Return ({relative path: bytes}, used names)."""
    files, used = {}, set()
    for template in sorted(p for p in TEMPLATES.rglob("*") if p.is_file()):
        rel = template.relative_to(TEMPLATES)
        files[rel] = render(template.read_text(), names, used, f"templates/{rel}").encode()
    for static in sorted(p for p in STATIC.rglob("*") if p.is_file()) if STATIC.exists() else []:
        rel = static.relative_to(STATIC)
        if rel in files:
            raise BuildError(f"{rel} comes from both templates/ and static/")
        files[rel] = static.read_bytes()
    return files, used


def luminance(hex_value):
    def channel(i):
        c = int(hex_value[i : i + 2], 16) / 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    return 0.2126 * channel(1) + 0.7152 * channel(3) + 0.0722 * channel(5)


def ratio(a, b):
    hi, lo = sorted((luminance(a), luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def contrast_rows(names, roles):
    """Yield (fg, bg, ratio, status) for every checked pair."""
    spec = roles["contrast"]
    minimum, allow = spec["minimum"], spec.get("allow", {})
    pairs = [(fg, bg) for fg in spec["text"] for bg in spec["surfaces"]]
    pairs += [(fg, spec["surfaces"][0]) for fg in spec.get("terminal", [])]
    pairs += [tuple(p) for p in spec.get("pairs", [])]
    for fg, bg in pairs:
        for name in (fg, bg):
            if name not in names:
                raise BuildError(f"[contrast] unknown colour {name!r}")
        r = ratio(names[fg], names[bg])
        status = "ok" if r >= minimum else ("allowed" if fg in allow else "FAIL")
        yield fg, bg, r, status


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail on stale or orphaned output")
    mode.add_argument("--list", action="store_true", help="print every colour name")
    mode.add_argument("--contrast", action="store_true", help="print the contrast report")
    args = parser.parse_args()

    try:
        names, roles = load_colors()

        if args.list:
            width = max(map(len, names))
            for name, value in names.items():
                print(f"{name:<{width}}  {value}")
            return 0

        rows = list(contrast_rows(names, roles))
        if args.contrast:
            allow = roles["contrast"].get("allow", {})
            for fg, bg, r, status in rows:
                note = f"  ({allow[fg]})" if status == "allowed" else ""
                print(f"{status:<8} {r:5.2f}  {fg} on {bg}{note}")
            return 1 if any(s == "FAIL" for *_, s in rows) else 0

        problems = [f"contrast {r:.2f} < {roles['contrast']['minimum']}: {fg} on {bg}"
                    for fg, bg, r, s in rows if s == "FAIL"]

        files, used = outputs(names)
        unused = sorted(set(roles["roles"]) - used)
        if unused:
            problems.append(f"roles not used by any template: {', '.join(unused)}")

        expected = {ROOT / rel for rel in files}
        orphans = sorted(
            p.relative_to(ROOT)
            for d in OWNED_DIRS if (ROOT / d).exists()
            for p in (ROOT / d).rglob("*") if p.is_file() and p not in expected
        )

        if args.check:
            stale = [rel for rel, data in files.items()
                     if not (ROOT / rel).exists() or (ROOT / rel).read_bytes() != data]
            problems += [f"stale: {rel}" for rel in stale]
            problems += [f"orphan: {rel} (no template or static file)" for rel in orphans]
        else:
            for rel, data in files.items():
                path = ROOT / rel
                path.parent.mkdir(parents=True, exist_ok=True)
                if not path.exists() or path.read_bytes() != data:
                    path.write_bytes(data)
                    print(f"wrote {rel}")
            problems += [f"orphan: {rel} (no template or static file)" for rel in orphans]

        if problems:
            for p in problems:
                print(f"error: {p}", file=sys.stderr)
            return 1
        if args.check:
            print(f"ok: {len(files)} files match colors.toml and roles.toml")
        return 0
    except BuildError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
