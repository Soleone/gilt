-- Solid blend of fg toward bg by t (0..1), for tinted backgrounds.
local function mix(fg, bg, t)
  local function ch(hex, i) return tonumber(hex:sub(i, i + 1), 16) end
  local out = "#"
  for _, i in ipairs({ 2, 4, 6 }) do
    out = out .. string.format("%02X", math.floor(ch(fg, i) + (ch(bg, i) - ch(fg, i)) * t + 0.5))
  end
  return out
end

